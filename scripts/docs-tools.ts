// Writes docs/tools.md from the tool definitions: pnpm docs:tools
import { writeFileSync } from 'node:fs';
import { z } from 'zod';
import { allTools } from '../src/tools/index.js';

const DOMAIN_TITLES: Record<string, string> = {
  session: 'Session',
  flow: 'Order flow',
  broker: 'Broker',
  foreign: 'Foreign flow',
  market: 'Market',
  price: 'Price and charts',
  company: 'Company',
  financial: 'Fundamentals',
  ownership: 'Ownership',
  corpaction: 'Corporate actions and calendar',
  screener: 'Screener',
  search: 'Search',
  stream: 'Stream and research',
  watchlist: 'Watchlists',
  alert: 'Alerts',
  account: 'Account (read only, needs the trading session)',
  order: 'Orders (real money: two confirmation popups, needs the trading session)',
  api: 'Whole catalog',
};

const tools = allTools();
const lines: string[] = [
  '# Tools',
  '',
  `stockbit-mcp offers ${tools.length} tools. This file is generated by \`pnpm docs:tools\`; do not edit it by hand.`,
  '',
];

for (const [domain, title] of Object.entries(DOMAIN_TITLES)) {
  const group = tools.filter((t) => t.domain === domain);
  if (group.length === 0) continue;
  lines.push(`## ${title}`, '');
  for (const tool of group) {
    const kind = tool.annotations.destructiveHint
      ? 'asks for confirmation / permission'
      : tool.annotations.readOnlyHint
        ? 'read only'
        : 'changes your lists';
    lines.push(`### \`${tool.name}\` — ${tool.title}`, '', `*${kind}*`, '');
    lines.push(tool.description.split('\n\n')[0] ?? '', '');
    const params = Object.entries(tool.inputSchema);
    if (params.length > 0) {
      lines.push('| Input | Required | Description |', '|---|---|---|');
      for (const [name, schema] of params) {
        const required = !(schema as z.ZodType).safeParse(undefined).success;
        const desc = ((schema as z.ZodType).description ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
        lines.push(`| \`${name}\` | ${required ? 'yes' : ''} | ${desc} |`);
      }
      lines.push('');
    }
    const endpoint = tool.description.match(/Endpoint: (.+)$/m)?.[1];
    if (endpoint) lines.push(`Endpoint: \`${endpoint.replace(/\.$/, '')}\``, '');
  }
}

writeFileSync(new URL('../docs/tools.md', import.meta.url), `${lines.join('\n')}\n`);
console.log(`docs/tools.md: ${tools.length} tools`);
